import { act, fireEvent, screen, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { api } from '../../lib/api'
import * as fx from '../../test/fixtures'
import { currentPath, renderPage, stubSession } from '../../test/utils'
import { StrategiesPage } from '../strategies/StrategiesPage'

const open = () => renderPage(<StrategiesPage />, { route: '/strategies?tab=arena', path: '/strategies' })
export const deferred = <T,>() => { let resolve!: (v: T) => void; let reject!: (e: Error) => void; const promise = new Promise<T>((a,b) => { resolve = a; reject = b }); return { promise, resolve, reject } }
beforeEach(() => {
  stubSession()
  vi.spyOn(api, 'autopilots').mockResolvedValue({ autopilots: [] })
  vi.spyOn(api, 'arenaOptions').mockResolvedValue(fx.arenaOptions)
  vi.spyOn(api, 'arenaRuns').mockResolvedValue({ runs: [] })
  vi.spyOn(api, 'liveArena').mockResolvedValue(fx.liveBoard())
  vi.spyOn(api, 'liveArenaSteps').mockResolvedValue({ steps: [fx.arenaStep(25, { t: 1791187200 })] })
  vi.spyOn(api, 'copyLiveAgent').mockResolvedValue({ plan: fx.copyPlan() })
})
afterEach(() => vi.useRealTimers())
describe('Live paper arena', () => {
  it('defaults to Live and fetches only the selected arena surface, preserving URL query on selection', async () => {
    const { user } = open()
    expect(await screen.findByRole('heading', { name: 'The live paper desk.' })).toBeInTheDocument()
    expect(api.arenaOptions).not.toHaveBeenCalled()
    expect(screen.getByRole('group', { name: 'Arena views' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Historical' }))
    expect(currentPath()).toBe('/strategies?tab=arena&arena=historical')
    expect(await screen.findByRole('heading', { name: /Let the agents trade the past/ })).toBeInTheDocument()
    expect(api.liveArena).toHaveBeenCalledTimes(1)
    await user.click(screen.getByRole('button', { name: 'Live' }))
    expect(currentPath()).toBe('/strategies?tab=arena')
  })
  it('keeps last loaded data after a failed refresh, shows UTC/history bounds and never exposes provider identity', async () => {
    vi.mocked(api.liveArena).mockResolvedValue(fx.liveBoard({ desk: { ...fx.liveDesk({ historyLimited: true }), model: 'secret-provider-id' } } as never))
    open()
    expect(await screen.findByRole('heading', { name: 'Trend Rider' })).toBeInTheDocument()
    expect(screen.getByText(/360 bars/)).toBeInTheDocument()
    expect(screen.getByText(/08:00.*UTC/)).toBeInTheDocument()
    expect(screen.queryByText(/secret-provider/)).not.toBeInTheDocument()
    vi.mocked(api.liveArena).mockRejectedValue(new Error('offline'))
    fireEvent(document, new Event('visibilitychange'))
    expect(await screen.findByRole('alert')).toHaveTextContent(/showing last loaded data/)
    expect(screen.getByRole('heading', { name: 'Trend Rider' })).toBeInTheDocument()
  })
  it('loads initial error, retry and starting/paused persisted states honestly', async () => {
    vi.mocked(api.liveArena).mockRejectedValueOnce(new Error('offline')).mockResolvedValue(fx.liveBoard({ desk: fx.liveDesk({ status: 'starting', lastStepAt: null }), agents: [], benchmarks: [] }))
    const { user } = open()
    await user.click(await screen.findByRole('button', { name: 'Retry' }))
    expect(await screen.findByText(/Awaiting the first decision/)).toBeInTheDocument()
    vi.mocked(api.liveArena).mockResolvedValue(fx.liveBoard({ desk: fx.liveDesk({ enabled: false, status: 'paused', nextStepAt: null }) }))
    fireEvent(document, new Event('visibilitychange'))
    expect(await screen.findByText(/paused on this server/)).toBeInTheDocument()
    expect(screen.getAllByRole('button', { name: 'Copy (paper)' }).every((b) => b.hasAttribute('disabled'))).toBe(true)
  })
  it('polls at 30 seconds only while visible, serializes requests and aborts on unmount', async () => {
    vi.useFakeTimers()
    const view = open()
    await act(async () => {})
    expect(api.liveArena).toHaveBeenCalledTimes(1)
    Object.defineProperty(document, 'hidden', { configurable: true, value: true })
    await act(async () => vi.advanceTimersByTime(30000))
    expect(api.liveArena).toHaveBeenCalledTimes(1)
    Object.defineProperty(document, 'hidden', { configurable: true, value: false })
    const pending = deferred<ReturnType<typeof fx.liveBoard>>()
    vi.mocked(api.liveArena).mockReturnValue(pending.promise)
    fireEvent(document, new Event('visibilitychange'))
    await act(async () => vi.advanceTimersByTime(60000))
    expect(api.liveArena).toHaveBeenCalledTimes(2)
    const signal = vi.mocked(api.liveArena).mock.calls.at(-1)![0]!
    view.unmount()
    expect(signal.aborted).toBe(true)
    pending.resolve(fx.liveBoard())
    await act(async () => {})
  })
  it('a new copy plan wins over an earlier deferred board poll and sends no catch-up order or credits', async () => {
    const old = deferred<ReturnType<typeof fx.liveBoard>>()
    const { user } = open()
    await screen.findByRole('heading', { name: 'Trend Rider' })
    vi.mocked(api.liveArena).mockReturnValueOnce(old.promise).mockResolvedValue(fx.liveBoard({ myPlans: [fx.copyPlan()] }))
    fireEvent(document, new Event('visibilitychange'))
    const order = vi.spyOn(api, 'placeOrder')
    await user.click(screen.getAllByRole('button', { name: 'Copy (paper)' })[0])
    const dlg = screen.getByRole('dialog', { name: 'Copy Trend Rider (paper)' })
    await user.click(within(dlg).getByRole('button', { name: 'Confirm copy (paper)' }))
    await screen.findByRole('link', { name: 'Manage in Account' })
    old.resolve(fx.liveBoard())
    await act(async () => {})
    expect(screen.getByRole('link', { name: 'Manage in Account' })).toBeInTheDocument()
    expect(api.copyLiveAgent).toHaveBeenCalledWith('live-momentum', { ratio: 0.1, maxUsd: 5000 })
    expect(order).not.toHaveBeenCalled()
  })
})
it.each(['stale', 'outage'] as const)('shows persisted %s health and a benched agent with its hold/error explanation', async (status) => {
  vi.mocked(api.liveArena).mockResolvedValue(fx.liveBoard({ desk: fx.liveDesk({ status, stale: status === 'stale', lastError: 'Stored market marks unavailable.' }), agents: [fx.liveAgent({ status: 'benched', errors: 3, benchedUntil: '2026-10-06T08:00:00Z', lastError: 'Model error; held.' })] }))
  open()
  expect(await screen.findByText('Stored market marks unavailable.')).toBeInTheDocument()
  expect(screen.getByText(/Persisted data/)).toBeInTheDocument()
  expect(screen.getByText(/Holding until 2026-10-06 08:00 UTC/)).toHaveTextContent('3 consecutive failures')
  expect(screen.getByRole('button', { name: 'Copy (paper)' })).toBeEnabled()
})
