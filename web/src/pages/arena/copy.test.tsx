import { act, fireEvent, screen, waitFor, within } from '@testing-library/react'
import { beforeEach, expect, it, vi } from 'vitest'
import { api, ApiError } from '../../lib/api'
import * as fx from '../../test/fixtures'
import { renderPage, stubSession } from '../../test/utils'
import { CopyButton, CopyPlanCard } from './copy'
import { LiveArena } from './LiveArena'
beforeEach(()=>stubSession())
it('blocks invalid inputs, accepts both endpoints and prevents duplicate submit/cancel mutation',async()=>{
  let resolve!: (p:{plan:ReturnType<typeof fx.copyPlan>})=>void
  const create=vi.spyOn(api,'copyLiveAgent').mockReturnValue(new Promise((r)=>{resolve=r}))
  const onCreated=vi.fn()
  const {user}=renderPage(<CopyButton agent={fx.liveAgent()} enabled onCreated={onCreated} onConflict={vi.fn()} />)
  await user.click(screen.getByRole('button',{name:'Copy (paper)'}))
  const dlg=screen.getByRole('dialog')
  expect(dlg).toHaveTextContent('Copies future fills only')
  const ratio=screen.getByLabelText('Copy ratio (%)'), cap=screen.getByLabelText('Deployed-value cap (USD)')
  await user.clear(ratio)
  expect(screen.getByRole('button',{name:'Confirm copy (paper)'})).toBeDisabled()
  await user.type(ratio,'100'); await user.clear(cap); await user.type(cap,'50001')
  expect(screen.getByRole('button',{name:'Confirm copy (paper)'})).toBeDisabled()
  await user.clear(cap); await user.type(cap,'50000')
  await user.click(screen.getByRole('button',{name:'Confirm copy (paper)'}))
  fireEvent.submit(dlg.querySelector('form')!)
  expect(create).toHaveBeenCalledTimes(1)
  expect(create).toHaveBeenCalledWith('live-momentum',{ratio:1,maxUsd:50000})
  expect(cap).toBeDisabled()
  const cancel = new Event('cancel',{cancelable:true}); dlg.dispatchEvent(cancel); expect(cancel.defaultPrevented).toBe(true)
  await act(async()=>resolve({plan:fx.copyPlan()}))
  expect(onCreated).toHaveBeenCalledWith(fx.copyPlan())
  await user.click(screen.getByRole('button',{name:'Copy (paper)'}))
  await user.click(screen.getByRole('button',{name:'Cancel'}))
  expect(create).toHaveBeenCalledTimes(1)
})
it('keeps a real conflict inline and refreshes ownership without removing the open dialog',async()=>{
  vi.spyOn(api,'liveArena').mockResolvedValueOnce(fx.liveBoard()).mockResolvedValue(fx.liveBoard({myPlans:[fx.copyPlan()]}))
  vi.spyOn(api,'copyLiveAgent').mockRejectedValue(new ApiError(409,'conflict','An active copy plan already exists for this agent.'))
  const {user}=renderPage(<LiveArena />)
  await user.click((await screen.findAllByRole('button',{name:'Copy (paper)'}))[0])
  await user.click(screen.getByRole('button',{name:'Confirm copy (paper)'}))
  expect(await screen.findByRole('alert')).toHaveTextContent('An active copy plan already exists for this agent.')
  await waitFor(()=>expect(api.liveArena).toHaveBeenCalledTimes(2))
  expect(screen.getByRole('dialog',{name:'Copy Trend Rider (paper)'})).toBeInTheDocument()
  fireEvent.submit(screen.getByRole('dialog').querySelector('form')!)
  expect(api.copyLiveAgent).toHaveBeenCalledTimes(1)
  await user.click(within(screen.getByRole('dialog')).getByRole('button',{name:'Cancel'}))
  expect(screen.getByRole('link',{name:'Manage in Account'})).toBeInTheDocument()
})
it.each([false,true])('stops keep/close=%s once and retains residual ownership/log from the returned plan',async(close)=>{
  const stopped=fx.copyPlan({status:'stopped',positions:[{symbol:'BTC',qty:0.01}],log:[{kind:'skip',t:'2026-10-05T10:00:00Z',text:'Quote unavailable; kept.'}]})
  const stop=vi.spyOn(api,'stopCopyPlan').mockResolvedValue({plan:stopped,trades:[],portfolio:{...fx.portfolio,revision:10}})
  const onChanged=vi.fn()
  const {user}=renderPage(<CopyPlanCard plan={fx.copyPlan()} onChanged={onChanged} onConflict={vi.fn()} />)
  await user.click(screen.getByRole('button',{name:'Stop copying'}))
  await user.click(screen.getByRole('button',{name:close ? 'Stop and close owned positions':'Stop and keep positions'}))
  expect(stop).toHaveBeenCalledWith('cp1',close)
  expect(onChanged).toHaveBeenCalledWith(stopped)
  expect(screen.getByRole('status')).toHaveTextContent('Copy plan stopped.')
})
it('retains the stop dialog and original plan on error and retries without claiming all positions closed',async()=>{
  const stop=vi.spyOn(api,'stopCopyPlan').mockRejectedValueOnce(new ApiError(500,'internal','Retry this stop.')).mockResolvedValue({plan:fx.copyPlan({status:'stopped'}),trades:[],portfolio:null})
  const {user}=renderPage(<CopyPlanCard plan={fx.copyPlan()} onChanged={vi.fn()} onConflict={vi.fn()} />)
  await user.click(screen.getByRole('button',{name:'Stop copying'}))
  await user.click(screen.getByRole('button',{name:'Stop and keep positions'}))
  expect(await screen.findByRole('alert')).toHaveTextContent('Retry this stop.')
  expect(screen.getByRole('dialog')).toHaveAttribute('open')
  await user.click(screen.getByRole('button',{name:'Stop and keep positions'}))
  expect(stop).toHaveBeenCalledTimes(2)
  expect(screen.queryByText('All positions closed')).toBeNull()
})
