it('retains the Stop conflict dialog when a fresh active-only board no longer contains that plan', async()=>{
  vi.spyOn(api,'liveArena').mockResolvedValueOnce(fx.liveBoard({myPlans:[fx.copyPlan()]})).mockResolvedValue(fx.liveBoard({myPlans:[]}))
  vi.spyOn(api,'stopCopyPlan').mockRejectedValue(new ApiError(409,'conflict','This copy plan is not active.'))
  const {user}=renderPage(<LiveArena />)
  await user.click(await screen.findByRole('button',{name:'Stop copying'}))
  await user.click(screen.getByRole('button',{name:'Stop and keep positions'}))
  expect(await screen.findByRole('alert')).toHaveTextContent('This copy plan is not active.')
  await waitFor(()=>expect(api.liveArena).toHaveBeenCalledTimes(2))
  const dialog=screen.getByRole('dialog',{name:'Stop copying Trend Rider?'})
  expect(dialog).toHaveAttribute('open')
  await user.click(within(dialog).getByRole('button',{name:'Cancel'}))
  expect(screen.queryByRole('region',{name:'Copy plan Trend Rider'})).toBeNull()
})
it('keeps the successful Stop outcome and refused-close residuals until Dismiss after active-only refresh', async()=>{
  vi.spyOn(api,'liveArena').mockResolvedValueOnce(fx.liveBoard({myPlans:[fx.copyPlan()]})).mockResolvedValue(fx.liveBoard({myPlans:[]}))
  const stopped=fx.copyPlan({status:'stopped',stopReason:'user',stoppedAt:'2026-10-05T10:00:00Z',positions:[{symbol:'BTC',qty:0.01}],log:[{t:'2026-10-05T10:00:00Z',kind:'skip',text:'BTC quote unavailable; position kept.'}]})
  vi.spyOn(api,'stopCopyPlan').mockResolvedValue({plan:stopped,trades:[],portfolio:null})
  const {user}=renderPage(<LiveArena />)
  await user.click(await screen.findByRole('button',{name:'Stop copying'}))
  await user.click(within(screen.getByRole('dialog')).getByRole('button',{name:'Stop and close owned positions'}))
  await waitFor(()=>expect(api.liveArena).toHaveBeenCalledTimes(2))
  await act(async()=>{})
  expect(screen.queryByRole('region',{name:'Stop result Trend Rider'})).not.toBeNull()
  const outcome=screen.getByRole('region',{name:'Stop result Trend Rider'})
  expect(outcome).toHaveTextContent('0.01 BTC')
  expect(outcome).toHaveTextContent('BTC quote unavailable; position kept.')
  expect(outcome).toHaveTextContent(/outcome at stop/i)
  expect(outcome).toHaveTextContent(/no longer protected/i)
  expect(within(outcome).getByRole('link',{name:'Review in Account'})).toHaveAttribute('href','/account#copy-plans')
  expect(screen.queryByRole('region',{name:'Copy plan Trend Rider'})).toBeNull()
  expect(screen.getAllByRole('button',{name:'Copy (paper)'})[0]).toBeEnabled()
  document.dispatchEvent(new Event('visibilitychange'))
  await waitFor(()=>expect(api.liveArena).toHaveBeenCalledTimes(3))
  expect(outcome).toBeInTheDocument()
  await user.click(within(outcome).getByRole('button',{name:'Dismiss'}))
  expect(screen.queryByRole('region',{name:'Stop result Trend Rider'})).toBeNull()
})
