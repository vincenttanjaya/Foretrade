it('preserves a loaded older-page completion boundary during a same-agent newest refresh', async()=>{
  vi.mocked(api.liveArenaSteps)
    .mockResolvedValueOnce({steps:Array.from({length:20},(_,i)=>fx.arenaStep(25-i))})
    .mockResolvedValueOnce({steps:[fx.arenaStep(5,{reasoning:'Loaded older boundary'})]})
    .mockResolvedValue({steps:Array.from({length:20},(_,i)=>fx.arenaStep(26-i,{reasoning:i===0 ? 'Newest refreshed decision' : `Refreshed ${26-i}`}))})
  const {rerender}=render(<LiveDecisionLog agent={fx.liveAgent()} agents={[]} onSwitch={vi.fn()} onClose={vi.fn()} />)
  fireEvent.click(await screen.findByRole('button',{name:'Load older'}))
  await screen.findByText('Loaded older boundary')
  expect(screen.getByText('End of available decision history.')).toBeInTheDocument()
  rerender(<LiveDecisionLog agent={fx.liveAgent({steps:27})} agents={[]} onSwitch={vi.fn()} onClose={vi.fn()} />)
  await screen.findByText('Newest refreshed decision')
  expect(screen.getByText('Loaded older boundary')).toBeInTheDocument()
  expect(screen.queryByRole('button',{name:'Load older'})).toBeNull()
  expect(screen.getByText('End of available decision history.')).toBeInTheDocument()
})
it('pages omitted decisions when empty history later receives a full newest page for the same owner', async()=>{
  vi.mocked(api.liveArenaSteps)
    .mockResolvedValueOnce({steps:[]})
    .mockResolvedValueOnce({steps:Array.from({length:20},(_,i)=>fx.arenaStep(21-i,{reasoning:`New decision ${21-i}`}))})
    .mockResolvedValue({steps:[fx.arenaStep(1,{reasoning:'Recovered decision 1'}),fx.arenaStep(0,{reasoning:'Recovered decision 0'})]})
  const {rerender}=render(<LiveDecisionLog agent={fx.liveAgent({steps:0,lastStepAt:null})} agents={[]} onSwitch={vi.fn()} onClose={vi.fn()} />)
  await screen.findByText('No decisions yet.')
  rerender(<LiveDecisionLog agent={fx.liveAgent({steps:22})} agents={[]} onSwitch={vi.fn()} onClose={vi.fn()} />)
  await screen.findByText('New decision 21')
  expect(screen.queryByRole('button',{name:'Load older'})).not.toBeNull()
  fireEvent.click(screen.getByRole('button',{name:'Load older'}))
  await screen.findByText('Recovered decision 0')
  expect(api.liveArenaSteps).toHaveBeenLastCalledWith('live-momentum',{limit:20,before:2},expect.any(AbortSignal))
  expect(screen.getByRole('list',{name:'Decision history'}).children).toHaveLength(22)
  expect(screen.getByText('End of available decision history.')).toBeInTheDocument()
})
it('restarts a disjoint newest window and pages the missing interval without false adjacent transitions', async()=>{
  const old=Array.from({length:20},(_,i)=>fx.arenaStep(19-i,{reasoning:`Old decision ${19-i}`,equity:100000,targets:[{symbol:'BTC',weightPct:10}]}))
  vi.mocked(api.liveArenaSteps)
    .mockResolvedValueOnce({steps:old})
    .mockResolvedValueOnce({steps:[]})
    .mockResolvedValueOnce({steps:Array.from({length:20},(_,i)=>fx.arenaStep(59-i,{reasoning:`Newest decision ${59-i}`,equity:140000,targets:[{symbol:'BTC',weightPct:70}]}))})
    .mockResolvedValueOnce({steps:Array.from({length:20},(_,i)=>fx.arenaStep(39-i,{reasoning:`Recovered gap ${39-i}`,equity:130000,targets:[{symbol:'BTC',weightPct:60}]}))})
    .mockResolvedValueOnce({steps:old})
    .mockResolvedValue({steps:[]})
  const {rerender}=render(<LiveDecisionLog agent={fx.liveAgent({steps:20})} agents={[]} onSwitch={vi.fn()} onClose={vi.fn()} />)
  fireEvent.click(await screen.findByRole('button',{name:'Load older'}))
  await screen.findByText('End of available decision history.')
  rerender(<LiveDecisionLog agent={fx.liveAgent({steps:60})} agents={[]} onSwitch={vi.fn()} onClose={vi.fn()} />)
  await screen.findByText('Newest decision 59')
  expect(screen.getByRole('list',{name:'Decision history'}).children).toHaveLength(20)
  expect(screen.queryByText('Old decision 0')).toBeNull()
  const boundary=screen.getByText('Newest decision 40').closest('li')!
  expect(within(boundary).getByText('BTC 70% target')).toBeInTheDocument()
  expect(within(boundary).queryByText('$40,000.00')).toBeNull()
  fireEvent.click(screen.getByRole('button',{name:'Load older'}))
  await screen.findByText('Recovered gap 20')
  expect(api.liveArenaSteps).toHaveBeenLastCalledWith('live-momentum',{limit:20,before:40},expect.any(AbortSignal))
  expect(within(boundary).getByText('BTC 60% → 70%')).toBeInTheDocument()
  expect(within(boundary).getByText('$10,000.00')).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button',{name:'Load older'}))
  await screen.findByText('Old decision 0')
  expect(api.liveArenaSteps).toHaveBeenLastCalledWith('live-momentum',{limit:20,before:20},expect.any(AbortSignal))
  fireEvent.click(screen.getByRole('button',{name:'Load older'}))
  await screen.findByText('End of available decision history.')
  expect(screen.getByRole('list',{name:'Decision history'}).children).toHaveLength(60)
})
