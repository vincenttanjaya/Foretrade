import { expect, expectAccessible, expectNoHorizontalScroll, test } from './fixtures'
import { API_URL } from './mock-api'

for (const theme of ['light', 'dark'] as const) {
  test(`combined Account snapshots follow copy fills, outcome stakes and reset in ${theme}`, { tag: '@mobile' }, async ({ page }, info) => {
    await page.addInitScript((value) => localStorage.setItem('theme', value), theme)
    await page.clock.install()
    await page.goto('/account')
    const health = page.locator('.card').filter({ has: page.getByText('Portfolio health', { exact: true }) })
    await expect(health).toContainText('revision 1')
    const created = await page.request.post(`${API_URL}/api/arena/live/agents/live-momentum/copy`, { data: { ratio: .1, maxUsd: 100 } })
    expect(created.status()).toBe(201)
    expect((await page.request.post(`${API_URL}/__e2e/live-step`, { data: { step: 27 } })).ok()).toBe(true)
    const opened = await page.request.post(`${API_URL}/api/forecasts/f-seed/market-position`, { data: { side: 'yes', stake: 100 } })
    expect(opened.status()).toBe(201)
    const { portfolio } = await opened.json()
    await page.clock.fastForward(30_000)
    await expect(health).toContainText(`revision ${portfolio.revision}`)
    await expect(health).toContainText('Prediction stakes$100')
    await expect(health).toContainText('whole-book risk is unknown')
    const plan = page.getByRole('region', { name: 'Copy plan Trend Rider' })
    await expect(plan).toContainText('Reconciled holdings:')
    await expect(plan).toContainText('BTC')
    const history = page.getByRole('table').filter({ has: page.getByRole('columnheader', { name: 'Notional / Fee' }) })
    await expect(history.getByRole('link', { name: 'Copy', exact: true })).toHaveAttribute('href', '/account#copy-plans')
    await expect(page.getByRole('heading', { name: '1 paper position' })).toBeVisible()
    await expect(page.getByRole('region', { name: 'Account summary' })).toContainText('In prediction markets')
    await expectAccessible(page)
    await expectNoHorizontalScroll(page)
    await page.goto('/portfolios/p-seed')
    const overlap = page.getByRole('region', { name: 'Overlap with what you hold' })
    await expect(overlap).toContainText(`revision ${portfolio.revision}`)
    await expect(overlap).toContainText('BTC · long')
    await expect(overlap).toContainText('50% of basket')
    await expect(overlap).toContainText('Outcome stakes are excluded.')
    await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
    await expectAccessible(page)
    await expectNoHorizontalScroll(page)
    await overlap.evaluate((element) => element.scrollIntoView({ block: 'start' }))
    const screenshot = info.outputPath(`combined-overlap-${theme}.png`)
    await page.screenshot({ path: screenshot })
    await info.attach('Combined live and prediction overlap', { path: screenshot, contentType: 'image/png' })
    await page.goto('/account')
    await page.getByRole('button', { name: 'Reset portfolio', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Reset portfolio', exact: true }).click()
    await expect(health).toContainText('Nothing to review yet')
    await expect(page.getByRole('heading', { name: '1 paper position' })).toHaveCount(0)
    await expect(page.getByText('No trades yet', { exact: true })).toBeVisible()
    await expect(plan).toContainText('No reconciled holdings.')
    await expectNoHorizontalScroll(page)
    await page.goto('/portfolios/p-seed')
    await expect(overlap).toContainText('No current cash-asset holdings to compare.')
    await expect(page.getByRole('heading', { name: '3 holdings, weighted by the AI' })).toBeVisible()
    await expectNoHorizontalScroll(page)
  })
}
