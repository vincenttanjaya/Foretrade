import { expect, expectAccessible, expectNoHorizontalScroll, test, type Page } from './fixtures'
import { API_URL, SEED } from './mock-api'
import type { Chat, ChatStreamRequest, Trade } from '../src/lib/types'

const fixture = async (page: Page, scenario: string) => expect((await page.request.post(`${API_URL}/__e2e/account-fixture`, { data: { scenario } })).ok()).toBe(true)
const fills = async (page: Page) => (await (await page.request.get(`${API_URL}/api/portfolio/trades?limit=200`)).json()).trades as Trade[]
async function ask(page: Page, message: string) {
  await page.getByLabel('Message the agent').fill(message)
  await page.getByLabel('Message the agent').press('Enter')
  await expect(page.getByRole('list', { name: 'Conversation' })).toBeVisible()
  await expect(page.getByRole('list', { name: 'Conversation' })).toHaveAttribute('aria-busy', 'false')
}
async function noAction(page: Page) {
  await expect(page.getByRole('button', { name: /Confirm (buy|sell) \(paper\)|Set alert|Set automation|Run forecast/ })).toHaveCount(0)
  await expectAccessible(page); await expectNoHorizontalScroll(page)
}

