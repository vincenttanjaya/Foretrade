  test(`owned account reviews ${theme}: current native image read costs three and reload keeps metadata only @mobile`, async ({ page }, info) => {
    await page.addInitScript(theme => localStorage.setItem('theme', theme), theme)
    const requests: ChatStreamRequest[] = []
    page.on('request', req => { if (req.url() === `${API_URL}/api/chat/stream`) requests.push(req.postDataJSON()) })
    await page.goto('/')
    const data = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 512; canvas.height = 256; const ctx = canvas.getContext('2d')!; ctx.fillStyle = '#fff'; ctx.fillRect(0, 0, 512, 256); ctx.fillStyle = '#236dca'; ctx.fillRect(50, 50, 300, 20); return canvas.toDataURL('image/jpeg').split(',')[1] })
    await page.getByLabel('Attach files or photos').setInputFiles({ name: 'review-chart.jpg', mimeType: 'image/jpeg', buffer: Buffer.from(data, 'base64') })
    await expect(page.getByRole('img', { name: 'Preview review-chart.jpg' })).toBeVisible()
    await page.getByLabel('Answer mode').selectOption('fast')
    await ask(page, 'Review my last trade and draft a forecast')
    await expect(page.getByRole('list', { name: 'Conversation' })).toContainText('Entry $3,000.60')
    expect(requests).toHaveLength(1); expect(requests[0].mode).toBe('fast'); expect(requests[0].attachments).toHaveLength(1)
    expect((await (await page.request.get(`${API_URL}/api/me`)).json()).credits.used).toBe(21)
    const id = page.url().split('/').at(-1)!
    const stored = (await (await page.request.get(`${API_URL}/api/chats/${id}`)).json()).chat as Chat
    expect(stored.messages[0].attachments).toEqual([expect.objectContaining({ name: 'review-chart.jpg', kind: 'image' })])
    expect(stored.messages[1].attachments).toEqual([])
    expect(JSON.stringify(stored)).not.toContain(requests[0].attachments![0].data)
    await noAction(page)
    await page.reload()
    await expect(page.getByRole('list', { name: 'Conversation' })).toContainText('review-chart.jpg')
    await expect(page.getByRole('img', { name: /Preview/ })).toHaveCount(0)
    await page.screenshot({ path: info.outputPath(`account-image-history-${theme}.png`) })
    await ask(page, 'Review my last trade')
    expect(requests).toHaveLength(2); expect(requests[1]).not.toHaveProperty('attachments')
    await noAction(page)
  })

