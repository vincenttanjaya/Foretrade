test('an empty decision dialog gains a newest page and can recover its omitted older rows', { tag: '@mobile' }, async ({ page }) => {
  await page.clock.install()
  let phase = 0
  const cursors: number[] = []
  await page.route('**/api/arena/live', async (route) => {
    const response = await route.fetch(), board = await response.json()
    board.agents[0].steps = phase ? 22 : 0
    board.agents[0].lastStepAt = phase ? '2026-10-05T12:00:00Z' : null
    await route.fulfill({ response, json: board })
  })
  await page.route('**/api/arena/live/agents/live-momentum/steps?*', (route) => {
    const before = new URL(route.request().url()).searchParams.get('before')
    if (before != null) cursors.push(Number(before))
    const steps = !phase ? [] : before == null ? Array.from({ length: 20 }, (_, i) => fx.arenaStep(21 - i, { reasoning: `New decision ${21 - i}` })) : before === '2' ? [fx.arenaStep(1, { reasoning: 'Recovered decision 1' }), fx.arenaStep(0, { reasoning: 'Recovered decision 0' })] : []
    return route.fulfill({ json: { steps } })
  })
  await page.goto('/strategies?tab=arena')
  await page.getByRole('button', { name: 'View decisions' }).first().click()
  const drawer = page.getByRole('dialog')
  await expect(drawer.getByText('No decisions yet.')).toBeVisible()
  phase = 1
  await page.clock.fastForward(30000)
  await expect(drawer.getByText('New decision 21')).toBeVisible()
  await drawer.getByRole('button', { name: 'Load older' }).click()
  await expect(drawer.getByText('Recovered decision 0')).toBeVisible()
  expect(cursors).toEqual([2])
  await expect(drawer.getByRole('list', { name: 'Decision history' }).locator(':scope > li')).toHaveCount(22)
  await expect(drawer.getByText('End of available decision history.')).toBeVisible()
  await expect(drawer.getByRole('button', { name: 'Load older' })).toHaveCount(0)
  await expectNoHorizontalScroll(page)
})

test('a disjoint newest decision dialog window pages the missing middle interval', { tag: '@mobile' }, async ({ page }) => {
  await page.clock.install()
  let phase = 0
  const cursors: number[] = []
  const old = Array.from({ length: 20 }, (_, i) => fx.arenaStep(19 - i, { reasoning: `Old decision ${19 - i}`, equity: 100000, targets: [{ symbol: 'BTC', weightPct: 10 }] }))
  await page.route('**/api/arena/live', async (route) => {
    const response = await route.fetch(), board = await response.json()
    board.agents[0].steps = phase ? 60 : 20
    await route.fulfill({ response, json: board })
  })
  await page.route('**/api/arena/live/agents/live-momentum/steps?*', (route) => {
    const before = new URL(route.request().url()).searchParams.get('before')
    if (before != null) cursors.push(Number(before))
    const steps = before === '0' ? [] : before === '40' ? Array.from({ length: 20 }, (_, i) => fx.arenaStep(39 - i, { reasoning: `Recovered gap ${39 - i}`, equity: 130000, targets: [{ symbol: 'BTC', weightPct: 60 }] })) : before === '20' || !phase ? old : Array.from({ length: 20 }, (_, i) => fx.arenaStep(59 - i, { reasoning: `Newest decision ${59 - i}`, equity: 140000, targets: [{ symbol: 'BTC', weightPct: 70 }] }))
    return route.fulfill({ json: { steps } })
  })
  await page.goto('/strategies?tab=arena')
  await page.getByRole('button', { name: 'View decisions' }).first().click()
  const drawer = page.getByRole('dialog'), history = drawer.getByRole('list', { name: 'Decision history' })
  await drawer.getByRole('button', { name: 'Load older' }).click()
  await expect(drawer.getByText('End of available decision history.')).toBeVisible()
  phase = 1
  await page.clock.fastForward(30000)
  await expect(drawer.getByText('Newest decision 59')).toBeVisible()
  await expect(history.locator(':scope > li')).toHaveCount(20)
  await expect(drawer.getByText('Old decision 0')).toHaveCount(0)
  const boundary = history.locator(':scope > li').filter({ hasText: 'Newest decision 40' })
  await expect(boundary.getByText('BTC 70% target')).toBeVisible()
  await expect(boundary).not.toContainText('$40,000.00')
  await drawer.getByRole('button', { name: 'Load older' }).click()
  await expect(drawer.getByText('Recovered gap 20')).toBeVisible()
  await expect(boundary.getByText('BTC 60% → 70%')).toBeVisible()
  await expect(boundary).toContainText('up $10,000.00')
  await drawer.getByRole('button', { name: 'Load older' }).click()
  await expect(drawer.getByText('Old decision 0')).toBeVisible()
  await drawer.getByRole('button', { name: 'Load older' }).click()
  await expect(drawer.getByText('End of available decision history.')).toBeVisible()
  expect(cursors).toEqual([0, 40, 20, 0])
  await expect(history.locator(':scope > li')).toHaveCount(60)
  await expectNoHorizontalScroll(page)
})
